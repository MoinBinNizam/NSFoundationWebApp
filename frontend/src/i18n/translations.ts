export const englishFromBangla = Object.fromEntries(Object.entries(bangla).map(([english, bengali]) => [bengali, english]));

export function translateText(value: string, language: Language): string {
  if (language !== 'bn') return englishFromBangla[value] || value;

  const dynamicTranslations: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Showing (\d+) of (\d+) records$/, (_whole, shown, total) => `দেখানো হচ্ছে ${shown} এর মধ্যে ${total} টি রেকর্ড`],
    [/^Year (\d{4})$/, (_whole, year) => `বছর ${year}`],
    [/^Final Shares \((\d{4})\)$/, (_whole, year) => `চূড়ান্ত শেয়ার (${year})`],
    [/^No reconciliation records generated for year (\d{4}) yet\.$/, (_whole, year) => `এখনও ${year} সালের কোনো হিসাব মেলানোর তথ্য তৈরি হয়নি।`],
    [/^Custody Accounts & Balances \((\d+)\)$/, (_whole, count) => `তহবিল হিসাব ও ব্যালেন্স (${count})`],
    [/^Projects Portfolio \((\d+)\)$/, (_whole, count) => `প্রকল্প তালিকা (${count})`],
    [/^Derived from (\d+) custody accounts$/, (_whole, count) => `${count}টি তহবিল হিসাব থেকে তৈরি`],
    [/^Across (\d+) projects \((\d+) Active\)$/, (_whole, projects, active) => `${projects}টি প্রকল্পে (${active}টি চলমান)`],
  ];
  for (const [pattern, translate] of dynamicTranslations) {
    const match = value.match(pattern);
    if (match) return translate(...match);
  }
  return bangla[value] || value;
}
